def _xlsx_col_to_dta(col: str) -> str:
    """Export column name -> `.dta` name (Stata renamed '#' and leading digits)."""
    return "nominee" if col == "2024nominee" else col.replace("#", "")


def load_raw_df() -> pd.DataFrame:
    """The `.dta` (37,240 rows) without IP / location columns, validated."""
    if not RAW_ZIP.exists():
        raise FileNotFoundError(f"wu2025 zip not found: {RAW_ZIP}")
    with zipfile.ZipFile(RAW_ZIP) as zf:
        reader_bytes = io.BytesIO(zf.read(DTA_MEMBER))
    reader = pd.io.stata.StataReader(reader_bytes)
    cols = [c for c in reader.variable_labels() if c not in ("IPAddress", "LocationLatitude", "LocationLongitude")]
    reader_bytes.seek(0)
    df = pd.read_stata(reader_bytes, columns=cols, convert_categoricals=False)
    if df["CaseID"].nunique() != N_RESPONDENTS or len(df) != N_RESPONDENTS * 2 * N_TASKS:
        raise ValueError(f"Expected {N_RESPONDENTS} respondents x 20 rows, got {df['CaseID'].nunique()} / {len(df)}")
    return df


def load_question_texts() -> dict[str, str]:
    """`.dta` column -> question text from the export's question row."""
    with zipfile.ZipFile(RAW_ZIP) as zf:
        x = pd.read_excel(io.BytesIO(zf.read(XLSX_MEMBER)), nrows=1, dtype=str)
    return OrderedDict((_xlsx_col_to_dta(str(c)), str(v)) for c, v in x.iloc[0].items())


def extract_respondent_df(raw_df: pd.DataFrame) -> pd.DataFrame:
    resp = raw_df.drop_duplicates("CaseID").reset_index(drop=True)
    if len(resp) != N_RESPONDENTS:
        raise ValueError(f"Expected {N_RESPONDENTS} respondents, got {len(resp)}")
    return resp


def _row_attribute(r: dict, k: str) -> str:
    if r[f"{k}money"] == 1:
        return ATTR_MONEY
    if r[f"{k}percent"] == 1:
        return ATTR_PERCENT
    return ATTR_LOCAL


def extract_choice_tasks_df(raw_df: pd.DataFrame) -> pd.DataFrame:
    """One row per answered task: respondent, task, attribute rows in display order, both plans' levels, choice."""
    records = []
    for case, g in raw_df.groupby("CaseID", sort=True):
        g = g.assign(q=g["question"].astype(int)).sort_values("q")
        rows = g.to_dict("records")
        if [r["q"] for r in rows] != list(range(1, 21)):
            raise ValueError(f"CaseID {case}: unexpected question numbers")
        for t in range(1, N_TASKS + 1):
            p1, p2 = rows[2 * t - 2], rows[2 * t - 1]
            attrs = [_row_attribute(p1, k) for k in "XYZ"]
            if attrs != [_row_attribute(p2, k) for k in "XYZ"] or sorted(attrs) != sorted([ATTR_MONEY, ATTR_PERCENT, ATTR_LOCAL]):
                raise ValueError(f"CaseID {case} task {t}: inconsistent attribute rows {attrs}")
            ans = p1["conjoint"]
            if ans != p2["conjoint"]:
                raise ValueError(f"CaseID {case} task {t}: profiles disagree on the answer")
            if ans == "":
                continue
            if ans not in CONJOINT_OPTIONS:
                raise ValueError(f"CaseID {case} task {t}: unexpected answer {ans!r}")
            code = CONJOINT_OPTIONS.index(ans) + 1
            if [p1["choice"], p2["choice"]] != [float(code == 1), float(code == 2)]:
                raise ValueError(f"CaseID {case} task {t}: choice flags disagree with the answer")
            records.append({"CaseID": case, "task": t, "attributes": attrs,
                            "plan1": [str(p1[k]) for k in "XYZ"], "plan2": [str(p2[k]) for k in "XYZ"], "choice_code": code})
    return pd.DataFrame(records)


def format_plan_description(attrs: list[str], levels: list[str]) -> str:
    return "; ".join(f"{a}: {lvl}" for a, lvl in zip(attrs, levels, strict=True))


def build_survey_audit_artifacts() -> tuple[pd.DataFrame, dict[str, list[str]], dict]:
    raw_df = load_raw_df()
    resp = extract_respondent_df(raw_df)
    texts = load_question_texts()
    tasks_df = extract_choice_tasks_df(raw_df)

    rows: list[dict[str, str]] = []
    tags_by_key: dict[str, list[str]] = {}
    items: dict[str, dict] = {}
    study_contexts: list[dict] = []

    def add(*, qid, csv_cols, family, block, n_answered, include, kev_type, context_source, note, question_text,
            in_block_db_text, options, tags, paired=None, paired_total=None, q_type="MC", selector="SAVR", samples=None):
        idx = len(rows)
        key = f"{idx}:{qid}"
        rows.append({
            "catalog_idx": str(idx), "QuestionID": qid, "csv_cols": ";".join(csv_cols), "n_cols": str(len(csv_cols)),
            "family": family, "BlockName": block, "n_subitems": "1", "n_answered": str(n_answered),
            "include": "True" if include else "False", "kev_type": kev_type if include else "",
            "context_source": context_source, "context_sep": "", "drop_options": "", "review_note": note,
            "QuestionText": question_text,
            "Context_preview": in_block_db_text if context_source == "in_block_db" else "", "Rows_preview": "",
            "Options_preview": f"[{len(options)}] " + " | ".join(o["option"] for o in options) if options else "",
        })
        if tags:
            tags_by_key[key] = list(tags)
        paired = paired or []
        items[key] = {
            "QuestionType": q_type, "Selector": selector, "rows": [], "options": options, "row_breakdowns": [],
            "qtext_variants": [], "db_variants": [], "opt_variant_sets": [], "paired_variants": paired,
            "paired_variants_total": paired_total if paired_total is not None else len(paired),
            "sample_texts": samples or [], "in_block_db_text": in_block_db_text,
        }
        if family == "0_DB":
            study_contexts.append({"qid": qid, "block": block, "is_question": False, "n_variants": 1,
                                   "preview": question_text[:140], "full_text": question_text})

    def add_conjoint():
        add(qid="conjoint_intro", csv_cols=[], family="0_DB", block="Conjoint", n_answered=N_RESPONDENTS, include=False,
            kev_type="", context_source="", question_text=CONJOINT_INTRO_TEXT, in_block_db_text="", options=[], tags=[],
            note="Background screen and bill message shown before the 10 tasks. Not in the export; text from the paper "
                 "(Section 2.2 and footnote 2), so page layout is unknown.", q_type="DB", selector="")
        groups: OrderedDict[tuple[str, str], list[int]] = OrderedDict()
        for r in tasks_df.itertuples(index=False):
            groups.setdefault((format_plan_description(r.attributes, r.plan1), format_plan_description(r.attributes, r.plan2)),
                              []).append(int(r.choice_code))
        ranked = sorted(groups.items(), key=lambda kv: -len(kv[1]))
        paired = [{
            "n": len(ch), "stem": CONJOINT_STEM, "in_block_db_qid": "conjoint_intro", "in_block_db_text": CONJOINT_INTRO_TEXT,
            "qid_texts": {}, "row_counts": [],
            "options": [{"option": "Choice 1", "description": d1, "count": ch.count(1)},
                        {"option": "Choice 2", "description": d2, "count": ch.count(2)}],
        } for (d1, d2), ch in ranked]
        first = tasks_df.iloc[0]
        n_unanswered = N_RESPONDENTS * N_TASKS - len(tasks_df)
        add(qid="plan_choice", csv_cols=["conjoint", "choice", "question", "X", "Y", "Z", "Xmoney", "Ymoney", "Zmoney",
                                         "Xpercent", "Ypercent", "Zpercent", "Monthly_Bill1", "Percentage_of_Renewables1",
                                         "Locally_Produced_Renewables1"],
            family=CHOICE, block="Conjoint", n_answered=len(tasks_df), include=True, kev_type="choice",
            context_source="in_block_db",
            note=(f"Included as choice: the experiment's outcome ({len(tasks_df):,} answered tasks from {N_RESPONDENTS:,} "
                  f"respondents; {n_unanswered} tasks unanswered; {len(groups):,} distinct displayed pairs, all previewed). "
                  "Stem from the export (without 'Task t/10:'). Attribute names from the paper; levels and row order from "
                  "the .dta (X / Y / Z = the three rows as displayed; order fixed per respondent)."),
            question_text=CONJOINT_STEM, in_block_db_text=CONJOINT_INTRO_TEXT,
            options=[{"option": "Choice 1", "description": format_plan_description(first.attributes, first.plan1),
                      "count": int((tasks_df.choice_code == 1).sum())},
                     {"option": "Choice 2", "description": format_plan_description(first.attributes, first.plan2),
                      "count": int((tasks_df.choice_code == 2).sum())}],
            tags=[], paired=paired, paired_total=len(groups))

    covered = set()
    for col in texts:
        if col == CONJOINT_POSITION:
            add_conjoint()
            continue
        if col in DEMOGRAPHIC_COLS:
            s = resp[col]
            vc = s[s != ""].value_counts()
            add(qid=col, csv_cols=[col], family="0_Demographics", block="Demographics", n_answered=int((s != "").sum()),
                include=False, kev_type="", context_source="", question_text=texts[col], in_block_db_text="",
                options=[{"option": str(k), "count": int(v)} for k, v in vc.items()] if len(vc) <= 60 else [],
                tags=[], note="Excluded: used for the persona (persona.py, dataset key wu2025) or a party follow-up not used there.")
            covered.add(col)
            continue
        if col not in Q:
            continue
        spec = Q[col]
        s = resp[col]
        answered = s[s != ""]
        if spec["family"] == "0_TE":
            add(qid=col, csv_cols=[col], family="0_TE", block="", n_answered=len(answered), include=False, kev_type="",
                context_source="", question_text=texts[col], in_block_db_text="", options=[], tags=[], note=spec["note"],
                q_type="TE", selector="", samples=[] if col == "comment" else answered.head(8).tolist())
            covered.add(col)
            continue
        unexpected = set(answered) - set(spec["options"])
        if unexpected:
            raise ValueError(f"{col}: answers not in the option list: {unexpected}")
        add(qid=col, csv_cols=[col], family=spec["family"], block="", n_answered=len(answered), include=spec["include"],
            kev_type=spec.get("kev_type", ""), context_source="", question_text=texts[col], in_block_db_text="",
            options=[{"option": o, "count": int((answered == o).sum())} for o in spec["options"]],
            tags=spec.get("tags", []), note=spec["note"])
        covered.add(col)

    missing = (set(Q) | set(DEMOGRAPHIC_COLS)) - covered
    if missing:
        raise ValueError(f"Specs without an export column: {sorted(missing)}")

    audit_df = pd.DataFrame(rows)
    return audit_df, tags_by_key, {"version": 2, "schema_kind": "question_audit",
                                   "study_contexts": {"__all__": study_contexts}, "items": items}


def write_wu2025_audit_files(out_dir: Path = WU_DIR) -> tuple[Path, Path, Path]:
    """Generate `question_audit.csv`, `question_tags.json`, `.audit_details.json`; refuses to overwrite review work."""
    audit_df, tags_by_key, details = build_survey_audit_artifacts()
    csv_path, tags_path, details_path = out_dir / "question_audit.csv", out_dir / "question_tags.json", out_dir / ".audit_details.json"
    for p in (csv_path, tags_path):
        if p.exists():
            raise FileExistsError(f"{p} exists and may hold review work; move it away first to regenerate.")
    audit_df.to_csv(csv_path, index=False)
    tags_path.write_text(json.dumps(tags_by_key, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    details_path.write_text(json.dumps(details, ensure_ascii=False), encoding="utf-8")
    return csv_path, tags_path, details_path


if __name__ == "__main__":
    for path in write_wu2025_audit_files():
        print(f"Wrote {path}")
